// Builds src/dims.js from the researched dimension files in src/data/ (source values in millimetres, output in metres).
// Run: node gen-dims.js   (then node build.js)
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, 'src', 'data');
const read = f => { const p = path.join(dir, f); return fs.existsSync(p) ? JSON.parse(fs.readFileSync(p, "utf8")) : []; };
const m = v => v == null ? null : Math.round(v) / 1000;
const out = {}, notes = [];
const base = v => ({ src: (v.src || [])[0] || null, conf: v.conf || null });
const tag = (v, re) => { const t = (v.feat || []).map(x => re.exec(x)).find(Boolean); return t ? +t[1] / 1000 : null; };

/* Values that no manufacturer publishes. They only steer the drawing (axle position), never the footprint. Marked est. */
const EST_FO = { hymerbml890: 1.15, touran: 0.9, sharan: 0.97, ram1500: 1.02 };
/* Front overhang share of (L - wheelbase) by body type, used only when a car's overhangs are unpublished. */
const FO_SHARE = { small: 0.56, hatch: 0.52, sedan: 0.46, kombi: 0.45, suv: 0.48, mpv: 0.50, pickup: 0.43 };

read('dims-cars.json').concat(read('dims-vans.json').filter(v => ['van', 'minibus', 'campervan', 'motorhome'].includes(v.cat))).forEach(v => {
  const o = { L: m(v.L), W: m(v.W), wb: m(v.wb) };
  if (v.fo != null) o.fo = m(v.fo);
  else { o.fo = EST_FO[v.id] != null ? EST_FO[v.id] : Math.round((v.L - v.wb) * (FO_SHARE[v.cat] || 0.5)) / 1000; o.est = 1; notes.push(v.id + ': front overhang estimated ' + o.fo); }
  const bed = tag(v, /^bed-length:(\d+)/); if (bed) o.bed = bed;
  out[v.id] = Object.assign(o, base(v));
});
read('dims-vans.json').forEach(v => {
  if (v.cat === 'caravan') out[v.id] = Object.assign({ L: m(v.Ltotal), W: m(v.W), Lbody: m(v.Lbody), axles: v.axles || 1 }, base(v));
  else if (v.cat === 'trailer') out[v.id] = Object.assign({ L: m(v.Ltotal), W: m(v.Wtotal), boxL: m(v.boxL), boxW: m(v.boxW), axles: v.axles || 1, out: (v.feat || []).includes('wheels-outside') ? 1 : 0 }, base(v));
  else if (v.cat === 'moto') out[v.id] = Object.assign({ L: m(v.L), W: m(v.W), wb: m(v.wb) }, base(v));
});

/* Gear: the drawing functions expect a fixed meaning of L and W per category (see draw.js), so each category is mapped by hand. */
const G = {}; read('dims-gear.json').forEach(v => { G[v.id] = v; });
const gear = (id, L, W, extra) => { const v = G[id]; if (!v) return; out[id] = Object.assign({ L: m(L), W: m(W) }, extra || {}, base(v)); if (v.conf === 'derived') out[id].est = 1; };
const part = (id, k) => { const v = G[id]; return v && v.parts && v.parts[k] != null ? v.parts[k] : null; };
Object.keys(G).forEach(id => { const v = G[id], c = v.cat;
  if (c === 'awning' || c === 'awningtent') gear(id, v.L, v.W);            // L along the vehicle, W = extension / depth
  else if (c === 'tableset') gear(id, Math.min(v.L, v.W), Math.max(v.L, v.W));   // L along the table, W across table and chairs
  else gear(id, Math.max(v.L, v.W), Math.min(v.L, v.W));                  // long side first
});

const prov = read('provisional.json'), missing = Object.keys(prov).filter(id => !out[id]);
missing.forEach(id => { out[id] = Object.assign({}, prov[id], { conf: 'provisional' }); });
if (missing.length) notes.push('STILL PROVISIONAL (' + missing.length + '): ' + missing.join(', '));

const js = '/* Generated by gen-dims.js from src/data/*.json. Researched dimensions in metres; src = source of the figures, est = part of the entry is an estimate. Do not edit by hand. */\nconst DIMS = {\n'
  + Object.keys(out).map(id => '  ' + id + ':' + JSON.stringify(out[id])).join(',\n') + '\n};\n';
if (process.argv.includes('--dry')) { console.log(js); } else { fs.writeFileSync(path.join(__dirname, 'src', 'dims.js'), js); }
console.log(Object.keys(out).length + ' entries written' + (notes.length ? '\n' + notes.join('\n') : ''));
module.exports = out;
