// Converts the one freely licensed, model-specific top view we found into the planner's drawing classes.
// Source: Openclipart item 338016 "Volkswagen Touran (2018)" by mrehmann, CC0 1.0 (public domain).
//   https://openclipart.org/detail/338016/volkswagen-touran-2018
// Usage: node gen-outline.js <downloaded.svg> <x0> <y0> <width> <height>   (bounding box of the body in the file's units)
//        node gen-outline.js <downloaded.svg> 0 0 1 1 --probe <page.html>   (writes a page for measuring that box in a browser)
// The file is read as text only; nothing but path geometry is taken from it.
const fs = require('fs'), path = require('path');
const [file, X0, Y0, BW, BH] = [process.argv[2], +process.argv[3], +process.argv[4], +process.argv[5], +process.argv[6]];
const src = fs.readFileSync(file, 'utf8').replace(/xlink:href="data:[^"]*"/g, '');
const attr = (a, k) => { const r = new RegExp('(?:^|\\s)' + k + '="([^"]*)"').exec(a); return r ? r[1] : null; };
const round = d => d.replace(/-?\d*\.\d+(?:e-?\d+)?|-?\d+(?:e-?\d+)?/g, n => String(Math.round(parseFloat(n) * 100) / 100)).replace(/\s+/g, ' ').trim();
const SKIP = new Set(['path229555-4', 'path229555-7-1', 'path459487']);            // drop shadow and the scale bar
const CLASS = fill => !fill || fill === 'none' ? 'd'
  : /^#1c71d8$/i.test(fill) ? 'b'                                                    // body
  : /^#(f2f2f2|f9f9f9|d1d2ce|c20102)$/i.test(fill) ? 'g'                             // glass and lamps
  : 'p';                                                                             // pillars, mirrors, grille: opaque panels
const out = []; let m; const re = /<path\b([\s\S]*?)\/>/g;
while ((m = re.exec(src))) {
  const a = m[1], id = attr(a, 'id'), d = attr(a, 'd'), st = attr(a, 'style') || '';
  if (!d || SKIP.has(id) || attr(a, 'transform')) continue;
  out.push({ c: CLASS((/(?:^|;)fill:([^;]+)/.exec(st) || [])[1]), d: round(d) });
}
/* The tracing draws symmetric shapes as two halves that meet on the centreline. Two separate elements leave a hairline seam,
   so each such pair becomes one element with two subpaths (filled in one pass, still no stroke along the centreline). */
const startOf = d => { const r = /^[mM]\s*(-?[\d.]+)[ ,](-?[\d.]+)/.exec(d); return r ? [+r[1], +r[2]] : null; };
const CY = Y0 + BH / 2;
for (let i = 0; i < out.length; i++) {
  const p = out[i], s = startOf(p.d); if (!s || p.c === 'd' || Math.abs(s[1] - CY) > 0.05) continue;
  const j = out.findIndex((q, k) => k > i && q.c === p.c && startOf(q.d) && Math.abs(startOf(q.d)[0] - s[0]) < 0.01 && Math.abs(startOf(q.d)[1] - CY) < 0.05);
  if (j > 0) {   // a leading relative "m x,y dx,dy" must become "M x,y l dx,dy" once it no longer opens the path data
    const abs = out[j].d.replace(/^m\s*(-?[\d.]+)[ ,]+(-?[\d.]+)[ ,]+(?=[-\d.])/, 'M$1,$2 l').replace(/^m/, 'M');
    p.d += ' ' + abs; out.splice(j, 1);
  }
}
/* document order of the tracing is kept: it already stacks body, surrounds, glass and lines correctly */
const svg = out.map(p => '<path class="' + p.c + '" d="' + p.d + '"/>').join('');
const probe = process.argv.indexOf('--probe');
if (probe > 0) {
  fs.writeFileSync(process.argv[probe + 1], '<!doctype html><meta charset="utf-8"><svg viewBox="0 0 297 210" width="1188"><g id="body">'
    + out.filter(p => p.c === 'b').map(p => '<path d="' + p.d + '"/>').join('') + '</g><g id="all" fill="none" stroke="#000" stroke-width=".2">' + out.map(p => '<path d="' + p.d + '"/>').join('') + '</g></svg>');
  console.log('probe page written,', out.length, 'paths');
} else {
  const js = `/* Generated by gen-outline.js. Real top-view outline of the VW Touran, traced by mrehmann and released as CC0 on Openclipart (item 338016).
   The body box of the tracing is stretched to the manufacturer's length and width; wheels are added at the real axle positions. */
const RAW = {touran:${JSON.stringify({ x: X0, y: Y0, w: BW, h: BH, svg })}};
Draw.FN.raw = function(L,W,m){
  const r=RAW[m.raw], f=n=>Math.round(n*10000)/10000, w=x=>'<rect class="h" x="'+f(x-.33)+'" y=".035" width=".66" height=".22" rx=".04"/>', wh=w(m.fo)+w(m.fo+m.wb);
  return '<g class="raw" transform="scale('+f(L/r.w)+' '+f(W/r.h)+') translate('+(-r.x)+' '+(-r.y)+')">'+r.svg+'</g>'+wh+'<g transform="translate(0 '+f(W)+') scale(1 -1)">'+wh+'</g>';
};
`;
  fs.writeFileSync(path.join(__dirname, 'src', 'outline.js'), js);
  console.log('src/outline.js written:', out.length, 'paths,', Math.round(js.length / 1024) + ' KB', JSON.stringify(out.reduce((n, p) => (n[p.c] = (n[p.c] || 0) + 1, n), {})));
}
